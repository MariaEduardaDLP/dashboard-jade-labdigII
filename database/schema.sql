-- Esquema inicial do Jade. Execute no SQL Editor do Supabase antes do primeiro uso.
CREATE TABLE IF NOT EXISTS public.events (
    sequence INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id VARCHAR(36) NOT NULL,
    message_id VARCHAR(32) NOT NULL,
    requested_at TIMESTAMPTZ NOT NULL,
    attended_at TIMESTAMPTZ,
    urgency INTEGER NOT NULL,
    CONSTRAINT uq_events_id UNIQUE (id),
    CONSTRAINT ck_events_urgency CHECK (urgency IN (1, 2, 3)),
    CONSTRAINT ck_events_attendance_order
        CHECK (attended_at IS NULL OR attended_at >= requested_at)
);

CREATE INDEX IF NOT EXISTS ix_events_id ON public.events (id);
CREATE INDEX IF NOT EXISTS ix_events_message_pending_fifo
    ON public.events (message_id, attended_at, sequence);

-- O painel público usa somente a chave publishable/anon. Nunca conceda INSERT,
-- UPDATE ou DELETE ao papel anon. O coletor escreve com a conexão PostgreSQL local.
ALTER TABLE public.events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.events FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.events_sequence_seq FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA public TO anon;
GRANT SELECT ON public.events TO anon;
DROP POLICY IF EXISTS "Public can read Jade dashboard events" ON public.events;
CREATE POLICY "Public can read Jade dashboard events"
    ON public.events
    FOR SELECT
    TO anon
    USING (true);
